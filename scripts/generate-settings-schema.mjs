#!/usr/bin/env node

import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const packageJsonPath = path.join(repoRoot, "package.json");
const outputPath = path.join(repoRoot, "src", "generated", "settingsSchema.ts");
const PREFIX = "testextension.";
const SUPPORTED = new Set(["boolean", "number", "string"]);

const posix = (p) => p.replace(/\\/g, "/");
const assertObj = (v, m) => {
  if (!v || typeof v !== "object" || Array.isArray(v)) {
    throw new Error(m);
  }
};
const stripPrefix = (k) => {
  if (!k.startsWith(PREFIX)) {
    throw new Error(`Setting key '${k}' does not start with '${PREFIX}'.`);
  }
  return k.slice(PREFIX.length);
};

async function main() {
  const pkg = JSON.parse(await fs.readFile(packageJsonPath, "utf8"));
  assertObj(pkg.contributes, "package.json is missing contributes.");
  assertObj(
    pkg.contributes.configuration,
    "package.json is missing contributes.configuration.",
  );
  assertObj(
    pkg.contributes.configuration.properties,
    "package.json is missing contributes.configuration.properties.",
  );

  const entries = [];
  for (const [confPath, desc] of Object.entries(
    pkg.contributes.configuration.properties,
  )) {
    assertObj(desc, `Setting descriptor for '${confPath}' must be an object.`);
    const { type, default: def, minimum, maximum } = desc;
    if (typeof type !== "string" || !SUPPORTED.has(type)) {
      continue;
    }

    if (type === "boolean" && typeof def !== "boolean") {
      throw new Error(
        `Setting '${confPath}' default must be a boolean when type is boolean.`,
      );
    }
    if (type === "number") {
      if (typeof def !== "number") {
        throw new Error(
          `Setting '${confPath}' default must be a number when type is number.`,
        );
      }
      if (minimum !== undefined && typeof minimum !== "number") {
        throw new Error(
          `Setting '${confPath}' minimum must be a number when provided.`,
        );
      }
      if (maximum !== undefined && typeof maximum !== "number") {
        throw new Error(
          `Setting '${confPath}' maximum must be a number when provided.`,
        );
      }
      if (
        typeof minimum === "number" &&
        typeof maximum === "number" &&
        minimum > maximum
      ) {
        throw new Error(
          `Setting '${confPath}' minimum cannot be greater than maximum.`,
        );
      }
    }
    if (type === "string" && typeof def !== "string") {
      throw new Error(
        `Setting '${confPath}' default must be a string when type is string.`,
      );
    }

    const description = desc.description ?? null;

    entries.push([
      stripPrefix(confPath),
      confPath,
      type,
      def ?? null,
      minimum ?? null,
      maximum ?? null,
      description,
    ]);
  }

  const out = [
    "// This file is auto-generated by scripts/generate-settings-schema.mjs.",
    "// Do not edit this file directly.",
    "",
    'export type GeneratedSettingType = "boolean" | "number" | "string";',
    "",
    "export type GeneratedSetting = {",
    "  configurationPath: string;",
    "  valueType: GeneratedSettingType;",
    "  defaultValue: boolean | number | string;",
    "  minimum: number | null;",
    "  maximum: number | null;",
    "  description: string | null;",
    "};",
    "",
    "export const GENERATED_SETTINGS_SCHEMA = {",
    ...entries.map(
      ([k, conf, t, d, min, max, desc]) =>
        `  ${JSON.stringify(k)}: { configurationPath: ${JSON.stringify(conf)}, valueType: ${JSON.stringify(t)}, defaultValue: ${JSON.stringify(d)}, minimum: ${JSON.stringify(min)}, maximum: ${JSON.stringify(max)}, description: ${JSON.stringify(desc)} },`,
    ),
    "} as const satisfies Record<string, GeneratedSetting>;",
    "",
  ].join("\n");

  await fs.mkdir(path.dirname(outputPath), { recursive: true });
  await fs.writeFile(outputPath, out, "utf8");
  console.log(`Generated ${posix(path.relative(repoRoot, outputPath))}`);
}

main().catch((err) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exitCode = 1;
});
